"""Configuração e inicialização não destrutiva do PostgreSQL (RNF-05).

As credenciais vêm de variáveis de ambiente, nunca do código.
CREATE TABLE IF NOT EXISTS não elimina nem altera tarefas existentes.
"""
import os

SCHEMA_SQL = """
CREATE TABLE IF NOT EXISTS tasks (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL CHECK (length(btrim(title)) > 0),
    description TEXT,
    status TEXT NOT NULL DEFAULT 'Aberta'
        CHECK (status IN ('Aberta', 'Concluída'))
)
"""


def connection_kwargs() -> dict:
    """Constrói a ligação sem imprimir credenciais e sem interpolar uma URL."""
    password = os.environ.get("DB_PASSWORD")
    if not password:
        raise RuntimeError("DB_PASSWORD não definida; configurar .env e Compose")
    return {
        "host": os.environ.get("DB_HOST", "db"),
        "port": int(os.environ.get("DB_PORT", "5432")),
        "dbname": os.environ.get("DB_NAME", "smarttasks"),
        "user": os.environ.get("DB_USER", "smarttasks"),
        "password": password,
        "connect_timeout": 5,
    }


def initialize_schema(connect_kwargs: dict) -> None:
    """Cria a tabela em falta antes dos pedidos HTTP, sem apagar dados."""
    import psycopg

    with psycopg.connect(**connect_kwargs) as conn:
        with conn.cursor() as cursor:
            cursor.execute(SCHEMA_SQL)
        # O contexto confirma a transação apenas se não houver erro.
